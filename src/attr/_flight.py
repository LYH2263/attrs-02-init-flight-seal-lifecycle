"""
The construction flight: a per-instance, field-sealing lifecycle for the
initializers generated by *attrs*.

While a generated ``__init__`` / ``__attrs_init__`` runs, the instance is
only half-built.  A `_Flight` records which lifecycle phase the construction
is currently in and which attribute storage names have already completed
their planned assignment (the *sealed* set).

The state is **instance-local**: the registry maps ``id(instance)`` to the
flight of exactly that instance (verified through a weak reference whenever
the instance supports weak references), and entries disappear as soon as
the construction finishes successfully.  There is no process-wide
``object.__setattr__`` replacement and no context-variable stack: two
threads constructing two different instances have two independent entries
and can never observe each other's current field.

The phases are:

``pre_init``
    ``__attrs_pre_init__`` is running; every attribute storage name is
    still unassigned.

``assigning``
    Fields are planned-assigned in MRO order; ``current`` is the storage
    name being assigned right now.

``validating``
    All planned assignments are done and sealed; the validators run as a
    batch.

``post_init``
    ``__attrs_post_init__`` is running; sealing is lifted, so that frozen
    classes keep their pinned ability to write through
    ``object.__setattr__`` from post-init.

``ready``
    Construction completed; the registry entry is removed and ordinary
    frozen / ``on_setattr`` semantics apply.

``aborted``
    A hook (converter, factory, validator, pre/post-init) or a sealing
    violation raised; the entry is kept so the abandoned instance can
    never be queried as ``ready``.

Explicit ``object.__setattr__`` calls cannot be intercepted per instance,
so the generated initializer calls `after_hook` immediately after each hook
that receives the instance.  It verifies that (a) sealed fields still hold
the exact object that was planned-assigned and (b) no unassigned field was
pre-written.  Writes through a *generated* ``__setattr__`` fail
immediately in `guard_setattr`; both routes raise the same public errors.
"""

from __future__ import annotations

import enum
import threading
import weakref

from typing import Any

from .exceptions import SealedAttributeError, UnassignedAttributeError


class InitPhase(str, enum.Enum):
    """
    Lifecycle phases of an instance under construction.

    Members are also plain strings (``str`` enum) so the phase can be
    compared to ``"assigning"`` directly.
    """

    PRE_INIT = "pre_init"
    ASSIGNING = "assigning"
    VALIDATING = "validating"
    POST_INIT = "post_init"
    READY = "ready"
    ABORTED = "aborted"

    def __str__(self) -> str:
        return self.value


# id(instance) -> _Flight.  Entries are created by the generated initializer
# and removed when the construction reaches "ready"; aborted constructions
# keep their entry until the abandoned instance is garbage collected.
_flights: dict[int, _Flight] = {}


class _Flight:
    """
    The instance-local construction state.

    Attributes:
        phase: Current `InitPhase`.
        current: Storage name being planned-assigned while in
            ``assigning``, else `None`.
        baseline: Mapping of sealed storage names to the exact object that
            the planned assignment produced; identity is compared after
            hooks to detect rewrites.
        names: All attribute storage names of the class, in planned
            (MRO/field) order.
        slot_names: The subset of *names* whose storage is a slot; the
            others live in the instance ``__dict__``.
    """

    __slots__ = (
        "_ref",
        "_strong",
        "baseline",
        "current",
        "names",
        "nameset",
        "owner_ident",
        "phase",
        "slot_descs",
        "slot_names",
    )

    def __init__(
        self,
        names: tuple[str, ...],
        slot_names: frozenset[str],
        slot_descs: dict[str, Any],
        has_pre_init: bool,
    ) -> None:
        self.phase = (
            InitPhase.PRE_INIT if has_pre_init else InitPhase.ASSIGNING
        )
        self.current: str | None = None
        self.baseline: dict[str, Any] = {}
        self.names = names
        self.nameset = frozenset(names)
        self.slot_names = slot_names
        # Member descriptors for the slot-backed names, resolved straight
        # from the class MRO so reads bypass user ``__getattr__`` hooks.
        self.slot_descs = slot_descs
        # The thread running the generated initializer.  Read-only queries
        # for the *current assigning field* only answer the owner thread, so
        # two threads constructing different instances can never observe
        # each other's current storage name.
        self.owner_ident = threading.get_ident()
        self._ref: weakref.ref[_Flight] | None = None
        # Only used for classes that do not support weak references
        # (slotted classes built with ``weakref_slot=False`` on CPython):
        # keeps the instance alive -- and therefore its id un-reusable --
        # for as long as an aborted entry lingers.
        self._strong: Any = None

    def belongs_to(self, inst: Any) -> bool:
        ref = self._ref
        if ref is not None:
            return ref() is inst

        return self._strong is inst


def _make_finalizer(key: int, flight: _Flight) -> Any:
    """
    Drop *flight*'s registry entry when its instance dies, unless the id was
    reused by a newer flight in the meantime.
    """

    def _finalize(_ref: Any) -> None:
        if _flights.get(key) is flight:
            _flights.pop(key, None)

    return _finalize


# ---------------------------------------------------------------------------
# Primitive transitions -- called by the generated initializer script.
# ---------------------------------------------------------------------------


def _resolve_slot_descs(
    inst: Any, slot_names: frozenset[str]
) -> dict[str, Any]:
    """
    Map each slot-backed name to its member descriptor by walking the MRO.
    """
    descs: dict[str, Any] = {}
    for klass in type(inst).__mro__:
        class_dict = getattr(klass, "__dict__", None)
        if class_dict is None:
            continue
        for name in slot_names:
            if name in descs:
                continue
            desc = class_dict.get(name)
            # Only genuine slot member descriptors: a subclass shadowing
            # the slot with a property/other descriptor must not be probed.
            if type(desc).__name__ == "member_descriptor":
                descs[name] = desc
    return descs


def begin(
    inst: Any,
    names: tuple[str, ...],
    slot_names: frozenset[str],
    has_pre_init: bool,
) -> _Flight:
    """
    Open a construction flight for *inst* and register it.
    """
    slot_descs = _resolve_slot_descs(inst, slot_names)
    flight = _Flight(names, slot_names, slot_descs, has_pre_init)
    key = id(inst)
    _flights[key] = flight
    try:
        flight._ref = weakref.ref(inst, _make_finalizer(key, flight))
    except TypeError:
        flight._strong = inst

    return flight


def assign(flight: _Flight, name: str) -> None:
    """
    Enter the planned assignment of storage name *name*.
    """
    flight.phase = InitPhase.ASSIGNING
    flight.current = name


def seal(flight: _Flight, inst: Any, name: str) -> None:
    """
    Mark *name* sealed with the value that was planned-assigned.

    If nothing actually reached the storage (only possible for exotic
    ``on_setattr`` behaviour), the name stays unsealed: a later hook write
    then fails as an unassigned early write rather than silently sticking.
    """
    present, value = _storage_get(flight, inst, name)
    if present:
        flight.baseline[name] = value


def validating(flight: _Flight) -> None:
    """
    Enter the batched validator phase.
    """
    flight.phase = InitPhase.VALIDATING
    flight.current = None


def post_init(flight: _Flight) -> None:
    """
    Enter the ``__attrs_post_init__`` phase and lift sealing: object.__setattr__
    writes are allowed again from here on.
    """
    flight.phase = InitPhase.POST_INIT
    flight.current = None
    flight.baseline.clear()


def finish(inst: Any, flight: _Flight) -> None:
    """
    Finish the flight successfully: forget it so the instance queries as
    ``ready``.
    """
    key = id(inst)
    if _flights.get(key) is flight:
        _flights.pop(key, None)
    flight.phase = InitPhase.READY
    flight.current = None
    flight._strong = None


def abort(flight: _Flight) -> None:
    """
    Mark the flight as aborted.  The registry entry is intentionally kept
    so the abandoned instance never queries as ``ready``.  For instances
    without weakref support the strong reference keeps their id from being
    reused while the entry lingers.
    """
    flight.phase = InitPhase.ABORTED
    flight.current = None


# ---------------------------------------------------------------------------
# Hook verification.
# ---------------------------------------------------------------------------


def _storage_get(flight: _Flight, inst: Any, name: str) -> tuple[bool, Any]:
    """
    Read *name* directly from the instance's storage, bypassing any user
    ``__getattr__``.  Return ``(present, value)``.
    """
    desc = flight.slot_descs.get(name)
    if name in flight.slot_names:
        if desc is None:
            return False, None
        try:
            return True, desc.__get__(inst, type(inst))
        except AttributeError:
            return False, None
    try:
        return True, inst.__dict__[name]
    except KeyError:
        return False, None
    except AttributeError:
        return False, None


def after_hook(flight: _Flight, inst: Any) -> None:
    """
    Verify the sealing invariants right after a hook that received *inst*.

    Sealed names must still hold the identical planned value; every other
    attribute storage name must still be absent.  Runs in the ``pre_init``,
    ``assigning`` and ``validating`` phases only -- sealing is lifted for
    ``post_init`` and there is nothing to check afterwards.
    """
    phase = flight.phase
    if (
        phase is InitPhase.POST_INIT
        or phase is InitPhase.READY
        or phase is InitPhase.ABORTED
    ):
        return

    baseline = flight.baseline
    slot_names = flight.slot_names
    slot_descs = flight.slot_descs
    # The field currently being planned-assigned has already been written but
    # is not sealed yet; its planned write is the legitimate one.
    current = flight.current
    try:
        instance_dict = inst.__dict__
    except AttributeError:
        instance_dict = None

    for name in flight.names:
        if name == current:
            continue
        if name in baseline:
            present, value = _storage_get(flight, inst, name)
            if not present or value is not baseline[name]:
                # Missing storage (a hook deleted the sealed field) is the
                # same violation as rewriting it.
                raise SealedAttributeError(name, phase)
        elif name in slot_names:
            desc = slot_descs.get(name)
            if desc is None:
                continue
            try:
                desc.__get__(inst, type(inst))
            except AttributeError:
                pass
            else:
                raise UnassignedAttributeError(name, phase)
        elif instance_dict is not None and name in instance_dict:
            raise UnassignedAttributeError(name, phase)


def guard_setattr(inst: Any, name: str) -> None:
    """
    Fail immediately when a *generated* ``__setattr__`` is used to write an
    attribute storage name while the construction is still sealed.

    Non-attribute names, the ``post_init`` phase and finished instances are
    left untouched so that ordinary ``on_setattr`` semantics are preserved.
    """
    flight = _flights.get(id(inst))
    if flight is None or not flight.belongs_to(inst):
        return

    phase = flight.phase
    if (
        phase is InitPhase.POST_INIT
        or phase is InitPhase.READY
        or phase is InitPhase.ABORTED
    ):
        return

    if name not in flight.nameset:
        return

    # The field currently being planned-assigned is allowed to receive its
    # own write (e.g. a converter assigning through a generated
    # ``__setattr__``): the planned assignment seals the final value right
    # after the hook returns.
    if phase is InitPhase.ASSIGNING and name == flight.current:
        return

    if phase is not InitPhase.VALIDATING and name not in flight.baseline:
        # Nothing is sealed yet in pre_init, and in assigning a name that
        # the plan has not reached is an early write.
        raise UnassignedAttributeError(name, phase)

    raise SealedAttributeError(name, phase)


# ---------------------------------------------------------------------------
# Read-only public queries (re-exported from attr / attrs).
# ---------------------------------------------------------------------------


def _lookup(inst: Any) -> _Flight | None:
    flight = _flights.get(id(inst))
    if flight is None:
        return None
    if not flight.belongs_to(inst):
        # The id was reused by a different, already-finished object.
        return None
    return flight


def get_init_phase(inst: Any) -> InitPhase:
    """
    Return the current construction flight phase of *inst*.

    Finished instances -- normally constructed, produced by `attr.assoc`,
    or restored via ``__setstate__`` -- query as `InitPhase.READY`.  An
    instance whose construction failed stays `InitPhase.ABORTED`.
    """
    flight = _lookup(inst)
    return InitPhase.READY if flight is None else flight.phase


def get_init_field(inst: Any) -> str | None:
    """
    Return the storage name (``Attribute.name``) currently being
    planned-assigned while *inst* is in the ``assigning`` phase.

    Returns `None` in every other phase, including ``validating`` and
    ``ready``.  A thread other than the one running the initializer never
    observes the current field of an instance under construction.
    """
    flight = _lookup(inst)
    if (
        flight is not None
        and flight.phase is InitPhase.ASSIGNING
        and flight.owner_ident == threading.get_ident()
    ):
        return flight.current
    return None
